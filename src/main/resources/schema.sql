-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- 博物馆文物修复台账（F1）
-- 设计要点：
--   1. 文物编号 artifact_code、项目编号 project_code 数据库级唯一约束，配合服务层幂等创建；
--   2. 所有撤销均为状态变更（status -> REVOKED），不做物理删除；
--   3. 借出/归还/修复/验收通过 status 状态机串联完整链路。
-- ============================================================

-- 文物档案：材质、年代、来源、保存等级
CREATE TABLE IF NOT EXISTS t_artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_code VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    material VARCHAR(64),
    era VARCHAR(64),
    source VARCHAR(255),
    preservation_level VARCHAR(32),
    status VARCHAR(32) NOT NULL DEFAULT 'IN_STOCK',
    remark VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_artifact_code UNIQUE (artifact_code)
);

-- 入藏登记：关联文物，记录照片、尺寸、库位
CREATE TABLE IF NOT EXISTS t_acquisition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acquisition_no VARCHAR(64) NOT NULL,
    artifact_id BIGINT NOT NULL,
    photos VARCHAR(2000),
    dimensions VARCHAR(255),
    storage_location VARCHAR(128),
    acquired_at TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'REGISTERED',
    remark VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_acquisition_no UNIQUE (acquisition_no)
);
CREATE INDEX IF NOT EXISTS idx_acquisition_artifact ON t_acquisition (artifact_id);

-- 借出/归还记录
CREATE TABLE IF NOT EXISTS t_loan_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_no VARCHAR(64) NOT NULL,
    artifact_id BIGINT NOT NULL,
    borrower VARCHAR(128) NOT NULL,
    purpose VARCHAR(500),
    lent_at TIMESTAMP,
    expected_return_at TIMESTAMP,
    returned_at TIMESTAMP,
    status VARCHAR(32) NOT NULL DEFAULT 'LENT',
    remark VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_loan_no UNIQUE (loan_no)
);
CREATE INDEX IF NOT EXISTS idx_loan_artifact ON t_loan_record (artifact_id);

-- 修复项目：委托人、修复方案
CREATE TABLE IF NOT EXISTS t_restoration_project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code VARCHAR(64) NOT NULL,
    artifact_id BIGINT NOT NULL,
    client_name VARCHAR(128) NOT NULL,
    plan VARCHAR(2000),
    status VARCHAR(32) NOT NULL DEFAULT 'PLANNED',
    accepted_at TIMESTAMP,
    remark VARCHAR(500),
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_project_code UNIQUE (project_code)
);
CREATE INDEX IF NOT EXISTS idx_project_artifact ON t_restoration_project (artifact_id);

-- 修复阶段结果
CREATE TABLE IF NOT EXISTS t_restoration_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    stage_order INT NOT NULL,
    stage_name VARCHAR(128) NOT NULL,
    result VARCHAR(2000),
    recorded_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_stage_project ON t_restoration_stage (project_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('museum-1', '博物馆文物修复台账：文物档案、入藏登记、借出归还、修复项目与阶段结果');
